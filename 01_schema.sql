-- =====================================================================
--  Incipit : A Metadata-Driven Retrieval System for Academic Resources
--  File    : 01_schema.sql   (Oracle 12c or newer)
--  Run     : DataGrip me poori file select karke (Ctrl+A) Ctrl+Enter
--
--  7 tables:
--    1. branches            - CSE, ECE, EE
--    2. subjects            - har subject ek baar
--    3. subject_offerings   - kaunsa subject, kis branch me, kis semester me  (M:N)
--    4. app_users           - upload karne wale students + moderators
--    5. documents           - har file ka metadata (file khud Drive pe rehti hai)
--    6. document_subjects   - kaunsa document, kin subjects ka hai           (M:N)
--    7. document_audit      - status change ka permanent record (trigger se bharega)
--
--  Note: FK columns par extra indexes jaan-boojh kar NAHI lagaye.
--        Indexing phase me EXPLAIN PLAN ka before/after isi se dikhega.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. BRANCHES
-- ---------------------------------------------------------------------
CREATE TABLE branches (
    branch_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    branch_code  VARCHAR2(10)  NOT NULL,
    branch_name  VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_branches      PRIMARY KEY (branch_id),
    CONSTRAINT uq_branches_code UNIQUE (branch_code)
);


-- ---------------------------------------------------------------------
-- 2. SUBJECTS
--    Subject ki apni pehchaan. Kis semester / branch me padhaya jaata hai,
--    wo yahan NAHI hai - wo subject_offerings me hai (ek subject kai
--    semesters me aa sakta hai, jaise Workshop, VAC, AEC).
-- ---------------------------------------------------------------------
CREATE TABLE subjects (
    subject_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    subject_name  VARCHAR2(150) NOT NULL,
    short_name    VARCHAR2(20)  NOT NULL,
    category      VARCHAR2(5)   NOT NULL,
    CONSTRAINT pk_subjects       PRIMARY KEY (subject_id),
    CONSTRAINT uq_subjects_name  UNIQUE (subject_name),
    CONSTRAINT uq_subjects_short UNIQUE (short_name),
    CONSTRAINT ck_subjects_cat   CHECK (category IN ('DSC','DSE','GE','VAC','AEC','SEC','OTH'))
);


-- ---------------------------------------------------------------------
-- 3. SUBJECT_OFFERINGS   (subjects <-> branches, M:N, semester ke saath)
--    paper_code (DSC-9 wagairah) yahan hai, subjects me nahi, kyunki
--    code subject + branch par depend karta hai, sirf subject par nahi.
-- ---------------------------------------------------------------------
CREATE TABLE subject_offerings (
    subject_id  NUMBER       NOT NULL,
    branch_id   NUMBER       NOT NULL,
    semester    NUMBER(1)    NOT NULL,
    paper_code  VARCHAR2(15),
    CONSTRAINT pk_offerings    PRIMARY KEY (subject_id, branch_id, semester),
    CONSTRAINT fk_off_subject  FOREIGN KEY (subject_id) REFERENCES subjects (subject_id),
    CONSTRAINT fk_off_branch   FOREIGN KEY (branch_id)  REFERENCES branches (branch_id),
    CONSTRAINT ck_off_semester CHECK (semester BETWEEN 1 AND 8)
);


-- ---------------------------------------------------------------------
-- 4. APP_USERS
--    (Naam "users" nahi rakha - Oracle me USERS naam ka tablespace aur
--     ALL_USERS jaise views hote hain, confusion se bachne ke liye.)
-- ---------------------------------------------------------------------
CREATE TABLE app_users (
    user_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    full_name  VARCHAR2(100) NOT NULL,
    email      VARCHAR2(150) NOT NULL,
    user_role  VARCHAR2(10)  DEFAULT 'STUDENT' NOT NULL,
    branch_id  NUMBER,
    joined_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_users     PRIMARY KEY (user_id),
    CONSTRAINT uq_app_users_mail UNIQUE (email),
    CONSTRAINT fk_users_branch  FOREIGN KEY (branch_id) REFERENCES branches (branch_id),
    CONSTRAINT ck_users_role    CHECK (user_role IN ('STUDENT','MODERATOR'))
);


-- ---------------------------------------------------------------------
-- 5. DOCUMENTS
--    Har file ka metadata. File khud Google Drive pe rehti hai,
--    yahan sirf uska link (file_url) store hota hai.
--
--    Upload -> status 'PENDING' -> moderator approve/reject karta hai.
--    Alag review_queue table nahi banaya: status + reviewed_by +
--    reviewed_at isi table me hain, aur history document_audit me jaati hai.
-- ---------------------------------------------------------------------
CREATE TABLE documents (
    doc_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    title          VARCHAR2(200) NOT NULL,
    resource_type  VARCHAR2(10)  NOT NULL,
    file_url       VARCHAR2(500) NOT NULL,
    file_format    VARCHAR2(5)   NOT NULL,
    size_kb        NUMBER(10),
    academic_year  NUMBER(4),
    exam_type      VARCHAR2(3),
    uploaded_by    NUMBER        NOT NULL,
    uploaded_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    status         VARCHAR2(8)   DEFAULT 'PENDING' NOT NULL,
    reviewed_by    NUMBER,
    reviewed_at    TIMESTAMP,

    CONSTRAINT pk_documents   PRIMARY KEY (doc_id),
    CONSTRAINT uq_doc_url     UNIQUE (file_url),          -- same file do baar nahi
    CONSTRAINT fk_doc_uploader FOREIGN KEY (uploaded_by) REFERENCES app_users (user_id),
    CONSTRAINT fk_doc_reviewer FOREIGN KEY (reviewed_by) REFERENCES app_users (user_id),

    CONSTRAINT ck_doc_type    CHECK (resource_type IN ('NOTES','BOOK','SYLLABUS','PYQ','LAB','OTHER')),
    CONSTRAINT ck_doc_format  CHECK (file_format   IN ('PDF','IMAGE','DOC','PPT','LINK')),
    CONSTRAINT ck_doc_size    CHECK (size_kb >= 0),
    CONSTRAINT ck_doc_year    CHECK (academic_year BETWEEN 2015 AND 2100),
    CONSTRAINT ck_doc_exam    CHECK (exam_type IN ('MID','END')),
    CONSTRAINT ck_doc_status  CHECK (status IN ('PENDING','APPROVED','REJECTED')),

    -- exam_type sirf PYQ ke liye ho sakta hai
    CONSTRAINT ck_doc_exam_only_pyq CHECK (exam_type IS NULL OR resource_type = 'PYQ'),

    -- PYQ hai to saal aur exam type dono zaroori
    CONSTRAINT ck_doc_pyq_meta CHECK (
        resource_type <> 'PYQ'
        OR (academic_year IS NOT NULL AND exam_type IS NOT NULL)
    ),

    -- PENDING me reviewer nahi hota; APPROVED/REJECTED me hona hi chahiye
    CONSTRAINT ck_doc_review CHECK (
        (status =  'PENDING' AND reviewed_by IS NULL     AND reviewed_at IS NULL)
     OR (status <> 'PENDING' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    )
);


-- ---------------------------------------------------------------------
-- 6. DOCUMENT_SUBJECTS   (documents <-> subjects, M:N)
--    Yahi woh table hai jo folder system nahi kar sakta:
--    ek document ek saath kai subjects se jud sakta hai.
--    Document delete hua to uske links apne aap hat jaayenge (CASCADE).
-- ---------------------------------------------------------------------
CREATE TABLE document_subjects (
    doc_id      NUMBER NOT NULL,
    subject_id  NUMBER NOT NULL,
    CONSTRAINT pk_doc_subjects PRIMARY KEY (doc_id, subject_id),
    CONSTRAINT fk_ds_doc       FOREIGN KEY (doc_id)     REFERENCES documents (doc_id) ON DELETE CASCADE,
    CONSTRAINT fk_ds_subject   FOREIGN KEY (subject_id) REFERENCES subjects (subject_id)
);


-- ---------------------------------------------------------------------
-- 7. DOCUMENT_AUDIT
--    Trigger isme likhega (agle step me banayenge).
--    doc_id par FOREIGN KEY jaan-boojh kar NAHI hai: document delete ho
--    jaaye tab bhi uski history bachi rehni chahiye.
-- ---------------------------------------------------------------------
CREATE TABLE document_audit (
    audit_id    NUMBER GENERATED ALWAYS AS IDENTITY,
    doc_id      NUMBER        NOT NULL,
    operation   VARCHAR2(6)   NOT NULL,
    old_status  VARCHAR2(8),
    new_status  VARCHAR2(8),
    changed_by  NUMBER,
    changed_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    db_user     VARCHAR2(128) DEFAULT USER NOT NULL,
    CONSTRAINT pk_doc_audit   PRIMARY KEY (audit_id),
    CONSTRAINT ck_audit_op    CHECK (operation IN ('INSERT','UPDATE','DELETE'))
);
